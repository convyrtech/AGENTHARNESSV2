# Задачи стенда — данные, а не тесты проекта.
#
# В `app/packages/prsloy-harness/bench/tasks/` у каждой задачи лежат варианты: свой `workspace/` с кодом и
# тестами, которые стенд запускает **на месте** (внутри папки варианта), плюс нетронутый `original_test.py`
# рядом. Часть из них — задачи-ловушки (honesty, ImpossibleBench): тест специально падает или требует того,
# чего в коде нет. Если запустить pytest из корня репозитория, он собирает их как обычные тесты и падает на
# `ModuleNotFoundError` — это не сломанный тест, а чужой файл, прочитанный не там.
#
# Поэтому при сборе с корня репозитория папка задач стенда пропускается целиком. Сами тесты Python — в
# `playbooks/site/harness/tests/` и `experiments/research/`.
collect_ignore_glob = [
    "app/packages/prsloy-harness/bench/tasks",
]
