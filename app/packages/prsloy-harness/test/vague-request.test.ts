// Расплывчатая просьба (этап 14): признаки ловятся узко — «что-то сломалось» и обычные просьбы не трогаем.
import { describe, expect, it } from "vite-plus/test";
import { READING_NAMED, VAGUE_MARKERS } from "../src/vague-request.ts";

describe("vague request markers", () => {
  it("vague: «что-нибудь», «на твой вкус», «придумай», «сам реши»", () => {
    for (const p of [
      "Сделай что-нибудь для моей кофейни.",
      "Сделай какую-нибудь игру",
      "Оформи на твой вкус",
      "Придумай, чем порадовать клиентов",
      "сама выбери, что лучше",
      "Сделай что-нибудь по своему усмотрению",
    ])
      expect(VAGUE_MARKERS.test(p), p).toBe(true);
  });

  it("not vague: a concrete request, «что-то сломалось», words inside other words", () => {
    for (const p of [
      "Сделай мне сайт-визитку. Я фотограф Анна, снимаю свадьбы.",
      "Почини, что-то не работает в калькуляторе",
      "Программа падает с какой-то ошибкой",
      "Сделай лендинг, цвет любой",
      "Посчитай продажи по месяцам",
      "Напридумывали тут всего",
    ])
      expect(VAGUE_MARKERS.test(p), p).toBe(false);
  });

  it("a named reading: «Понял так», «исходил из», «если иначе — скажи»", () => {
    for (const a of [
      "Понял так: нужна страница с меню. Если иначе — скажи.",
      "Сделал визитку. Исходил из того, что нужен сайт.",
      "Готово. Если нужно иначе — напиши.",
      "Я понял, что нужен бот.",
    ])
      expect(READING_NAMED.test(a), a).toBe(true);
    for (const a of ["Готово! Сделал сайт для кофейни.", "Страница в index.html, открывай."])
      expect(READING_NAMED.test(a), a).toBe(false);
  });
});
